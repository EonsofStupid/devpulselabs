//! The MIXED-EXPORT drill (DG1) — real ffmpeg cuts a real session into a
//! clip step, and the exported player is walked in REAL headless Chrome
//! via dpl-engine-browser (the G1 browser-drill law, dogfooding DEMO-B).
//! Ignored by default (needs ffmpeg on PATH + an installed browser):
//!
//! ```text
//! cargo test -p dpl-guide --test mixed_export_drill -- --ignored --nocapture
//! ```

use std::path::{Path, PathBuf};
use std::process::Command;

fn ffmpeg(args: &[&str]) {
    let status = Command::new("ffmpeg")
        .args(["-y", "-v", "error"])
        .args(args)
        .status()
        .expect("ffmpeg on PATH");
    assert!(status.success(), "ffmpeg {args:?}");
}

fn scratch() -> PathBuf {
    let dir = std::env::temp_dir().join(format!("dpl-mixed-drill-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

fn file_url(p: &Path) -> String {
    format!("file:///{}", p.display().to_string().replace('\\', "/"))
}

#[test]
#[ignore = "live drill: needs ffmpeg on PATH + an installed chromium-family browser"]
fn a_mixed_guide_exports_and_the_player_walks_in_real_chrome() {
    let root = scratch();

    // Real stills + a real 4 s session, all generated by ffmpeg.
    let src = root.join("guide-src");
    std::fs::create_dir_all(&src).unwrap();
    ffmpeg(&[
        "-f",
        "lavfi",
        "-i",
        "color=c=red:s=320x240",
        "-frames:v",
        "1",
        src.join("a.webp").to_str().unwrap(),
    ]);
    ffmpeg(&[
        "-f",
        "lavfi",
        "-i",
        "color=c=blue:s=320x240",
        "-frames:v",
        "1",
        src.join("b.webp").to_str().unwrap(),
    ]);
    let session = root.join("session-src");
    std::fs::create_dir_all(&session).unwrap();
    ffmpeg(&[
        "-f",
        "lavfi",
        "-i",
        "testsrc=duration=4:size=320x240:rate=15",
        "-pix_fmt",
        "yuv420p",
        session.join("session.mp4").to_str().unwrap(),
    ]);
    std::fs::write(
        session.join("events.jsonl"),
        "{\"ms\":1000,\"type\":\"route-changed\",\"hub\":\"present\",\"sub\":\"shows\"}\n",
    )
    .unwrap();

    // still · replay(1.0→2.5 s) · still — the operator's ordered mix.
    std::fs::write(
        src.join("guide.json"),
        serde_json::to_vec_pretty(&serde_json::json!({
            "kind": "guide", "name": "mixed-drill", "stepCount": 3,
            "steps": [
                { "order": 1, "file": "a.webp", "action": "click",
                  "caption": "click here" },
                { "order": 2, "file": "", "kind": "replay",
                  "clipIn": 1.0, "clipOut": 2.5, "action": "",
                  "caption": "watch it happen" },
                { "order": 3, "file": "b.webp", "action": "marked",
                  "caption": "the payoff" },
            ],
        }))
        .unwrap(),
    )
    .unwrap();

    let out = root.join("mixed-share");
    let e = dpl_guide::export_guide(&src, Some(&session), &out, dpl_guide::ExportOpts::default())
        .expect("mixed export");
    assert_eq!(e.steps, 3);

    // The cut clip landed, ordered in place; every ffmpeg leg is real.
    let clip = out.join("step-002.mp4");
    assert!(clip.is_file() && std::fs::metadata(&clip).unwrap().len() > 0);
    assert!(out.join("step-001.webp").is_file());
    assert!(out.join("step-003.webp").is_file());
    assert!(out.join("guide-video.mp4").is_file(), "interleaved render");
    assert!(out.join("replay.gif").is_file(), "social clip");
    let m = dpl_guide::load_guide(&out).unwrap();
    assert_eq!(m.steps[1].clip.as_deref(), Some("step-002.mp4"));
    eprintln!("drill: export complete at {}", out.display());

    // Walk the player in REAL headless Chrome.
    let mut browser = dpl_engine_browser::Browser::launch(&dpl_engine_browser::BrowserConfig {
        window: (900, 700),
        ..Default::default()
    })
    .expect("browser");
    {
        let mut page = browser.new_page().unwrap();
        page.navigate(&file_url(&e.html)).unwrap();
        assert_eq!(page.evaluate("STEPS.length").unwrap(), serde_json::json!(3));
        assert_eq!(
            page.evaluate("document.getElementById('stepv').style.display||'none'")
                .unwrap(),
            serde_json::json!("none"),
            "step 1 is a still"
        );
        page.evaluate("document.getElementById('next').click()")
            .unwrap();
        assert_eq!(
            page.evaluate("document.getElementById('stepv').style.display")
                .unwrap(),
            serde_json::json!("block"),
            "step 2 plays the clip"
        );
        let src_kind = page
            .evaluate("document.getElementById('stepv').src.slice(0,15)")
            .unwrap();
        assert_eq!(src_kind, serde_json::json!("data:video/mp4;"), "embedded");
        page.evaluate("document.getElementById('next').click()")
            .unwrap();
        assert_eq!(
            page.evaluate("document.getElementById('stepv').style.display")
                .unwrap(),
            serde_json::json!("none"),
            "step 3 is a still again — one ordered sequence"
        );
        eprintln!("drill: player walked still → clip → still in real Chrome");
    }
    browser.close().unwrap();
    let _ = std::fs::remove_dir_all(&root);
}
